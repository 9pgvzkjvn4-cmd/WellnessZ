const TABLE: Record<string, WellbeingStrings> = { en, fr, ar };

export function wellbeingStrings(lang: string | undefined): WellbeingStrings {
  return TABLE[baseLang(lang)] ?? en;
}

/** Localised error text: clinical-content and consent rejections get friendly wording; server detail is never shown. */
export function wellbeingErrorText(lang: string, e: unknown): string {
  if (e instanceof ApiError && e.status === 422) {
    const code = e.problem?.code ?? '';
    if (code.startsWith('clinical_content')) return wellbeingStrings(lang).clinicalContent;
    if (code.startsWith('consent')) return wellbeingStrings(lang).consentRequired;
  }
  return errorText(portalStrings(lang), e);
}

/** "2 h 15 min" from minutes. */
export function durationText(t: WellbeingStrings, minutes: number): string {
  const m = Math.max(0, Math.round(minutes));
  return t.teDuration(Math.floor(m / 60), m % 60);
}
