#!/usr/bin/env python3
"""
Build the WellnessZ DEMO PACK.

    python3 demo/build.py

For every app in demo/src/*.html it writes demo/dist/<app>.html with the shared CSS and
JavaScript inlined, so each app is ONE file that opens offline by double-click (file://).
The demo data stays a separate file: demo/data/demo-data.js is copied to
demo/dist/demo-data.js and every app loads it with <script src="demo-data.js">.

It also:
  * validates demo/scenarios.json and writes demo/shared/scenarios.js (inlined into every app
    so the demo toolbar can show "next scenario step" hints);
  * builds demo/dist/index.html, the launcher (src/index.html), with the list of apps that
    were actually built.

Markers in the source HTML:
  <link rel="stylesheet" href="../shared/x.css" data-wz-inline>     -> <style>…</style>
  <script src="../shared/x.js" data-wz-inline></script>             -> <script>…</script>
  <script src="../data/demo-data.js" data-wz-data></script>         -> <script src="demo-data.js"></script>
  <!-- wz:built-apps -->                                            -> window.WZ_BUILT_APPS = [...]
No third-party tools are needed; Python 3.8+ only.
"""
import json
import pathlib
import re
import shutil
import sys

ROOT = pathlib.Path(__file__).resolve().parent
SRC = ROOT / "src"
SHARED = ROOT / "shared"
DATA = ROOT / "data"
DIST = ROOT / "dist"

APP_ORDER = ["employee-app", "manager-workspace", "oh-workspace", "partner-portal"]

LINK_RE = re.compile(r'<link\s+rel="stylesheet"\s+href="([^"]+)"\s+data-wz-inline\s*/?>')
SCRIPT_RE = re.compile(r'<script\s+src="([^"]+)"\s+data-wz-inline\s*>\s*</script>')
DATA_RE = re.compile(r'<script\s+src="[^"]*demo-data\.js"\s+data-wz-data\s*>\s*</script>')


def fail(msg):
    print("build.py: ERROR: " + msg, file=sys.stderr)
    sys.exit(1)


def write_scenarios():
    path = ROOT / "scenarios.json"
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        fail("scenarios.json is not valid JSON: %s" % exc)
    scenarios = data.get("scenarios") or []
    for sc in scenarios:
        for key in ("id", "title", "personas", "steps"):
            if key not in sc:
                fail("scenario %s is missing '%s'" % (sc.get("id", "?"), key))
        for i, st in enumerate(sc["steps"]):
            for key in ("app", "user", "action", "expected", "data"):
                if key not in st:
                    fail("scenario %s step %d is missing '%s'" % (sc["id"], i + 1, key))
    js = ("/* Generated by demo/build.py from demo/scenarios.json - do not edit. */\n"
          "window.WZ_SCENARIOS = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n")
    (SHARED / "scenarios.js").write_text(js, encoding="utf-8")
    return len(scenarios)


def safe_script(text):
    # A literal "</script" inside inlined JavaScript would end the element early.
    return re.sub(r"</(script)", r"<\\/\1", text, flags=re.IGNORECASE)


def inline(html, src_file, built_apps):
    base = src_file.parent

    def css(m):
        p = (base / m.group(1)).resolve()
        if not p.exists():
            fail("%s: stylesheet not found: %s" % (src_file.name, m.group(1)))
        return "<style>/* inlined from %s */\n%s\n</style>" % (p.name, p.read_text(encoding="utf-8"))

    def js(m):
        p = (base / m.group(1)).resolve()
        if not p.exists():
            fail("%s: script not found: %s" % (src_file.name, m.group(1)))
        return "<script>/* inlined from %s */\n%s\n</script>" % (p.name, safe_script(p.read_text(encoding="utf-8")))

    out = LINK_RE.sub(css, html)
    out = SCRIPT_RE.sub(js, out)
    out, n = DATA_RE.subn('<script src="demo-data.js"></script>', out)
    if n != 1:
        fail("%s: expected exactly one demo-data.js script tag with data-wz-data (found %d)" % (src_file.name, n))
    out = out.replace("<!-- wz:built-apps -->",
                      "<script>window.WZ_BUILT_APPS = %s;</script>" % json.dumps(built_apps))
    if "data-wz-inline" in out:
        fail("%s: an inline marker was not resolved" % src_file.name)
    return out


def main():
    if not (DATA / "demo-data.js").exists():
        fail("demo/data/demo-data.js not found")
    count = write_scenarios()
    DIST.mkdir(exist_ok=True)

    apps = [n for n in APP_ORDER if (SRC / (n + ".html")).exists()]
    others = sorted(p.stem for p in SRC.glob("*.html") if p.stem not in APP_ORDER and p.stem != "index")
    built = apps + others

    shutil.copyfile(DATA / "demo-data.js", DIST / "demo-data.js")
    report = []
    for name in built + ["index"]:
        src = SRC / (name + ".html")
        if not src.exists():
            continue
        html = inline(src.read_text(encoding="utf-8"), src, built)
        target = DIST / (name + ".html")
        target.write_text(html, encoding="utf-8")
        report.append((target.name, target.stat().st_size))

    print("WellnessZ demo pack built in %s" % DIST)
    print("  scenarios: %d" % count)
    for fname, size in report:
        print("  %-26s %7.1f kB" % (fname, size / 1024))
    print("  %-26s %7.1f kB (demo data file, kept separate)" % ("demo-data.js", (DIST / "demo-data.js").stat().st_size / 1024))
    missing = [n for n in APP_ORDER if n not in apps]
    if missing:
        print("  not yet built (no source in demo/src): " + ", ".join(missing))


if __name__ == "__main__":
    main()
