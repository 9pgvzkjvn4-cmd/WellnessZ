#!/usr/bin/env python3
"""
Build the WellnessZ DEVICE INTEGRATION DEMO PACK (E31–E34).

    python3 demo-devices/build.py

For every app in demo-devices/src/*.html it writes demo-devices/dist/<app>.html with the shared CSS and JavaScript
inlined, so each app is ONE file that opens offline by double-click (file://) in Chrome or Edge – no server, no CDN.
The demo data stays a separate file: demo-devices/data/device-demo-data.js is copied to dist/device-demo-data.js and
every app loads it with <script src="device-demo-data.js">.

It also:
  * validates scenarios.json and writes shared/scenarios.js (window.WZ_DEVICE_SCENARIOS, inlined into every app so the
    demo toolbar can show "next step" hints);
  * checks that the copied design system (shared/ui.css, shared/ui.js) still matches demo/shared (warning only – the
    device pack is independent and keeps its own copy);
  * builds dist/index.html, the launcher, with the list of apps that were actually built.

Markers in the source HTML:
  <link rel="stylesheet" href="../shared/x.css" data-wz-inline>     -> <style>…</style>
  <script src="../shared/x.js" data-wz-inline></script>             -> <script>…</script>
  <script src="../data/device-demo-data.js" data-wz-data></script>  -> <script src="device-demo-data.js"></script>
  <!-- wz:built-apps -->                                            -> window.WZ_BUILT_APPS = [...]
Python 3.8+ only, no third-party packages.
"""
import json
import pathlib
import re
import shutil
import sys

ROOT = pathlib.Path(__file__).resolve().parent
SRC, SHARED, DATA, DIST = ROOT / "src", ROOT / "shared", ROOT / "data", ROOT / "dist"
APP_ORDER = ["device-console", "integration-lab", "security-console"]
APPS_OF_STEPS = {"console", "lab", "security"}

LINK_RE = re.compile(r'<link\s+rel="stylesheet"\s+href="([^"]+)"\s+data-wz-inline\s*/?>')
SCRIPT_RE = re.compile(r'<script\s+src="([^"]+)"\s+data-wz-inline\s*>\s*</script>')
DATA_RE = re.compile(r'<script\s+src="[^"]*device-demo-data\.js"\s+data-wz-data\s*>\s*</script>')


def fail(msg):
    print("build.py: ERROR: " + msg, file=sys.stderr)
    sys.exit(1)


def write_scenarios():
    try:
        data = json.loads((ROOT / "scenarios.json").read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        fail("scenarios.json is not valid JSON: %s" % exc)
    scenarios = data.get("scenarios") or []
    if not 8 <= len(scenarios) <= 10:
        fail("expected 8–10 scenarios, found %d" % len(scenarios))
    ids = set()
    for sc in scenarios:
        for key in ("id", "code", "title", "summary", "personas", "steps"):
            if key not in sc:
                fail("scenario %s is missing '%s'" % (sc.get("id", "?"), key))
        if sc["id"] in ids:
            fail("duplicate scenario id " + sc["id"])
        ids.add(sc["id"])
        for i, st in enumerate(sc["steps"]):
            for key in ("app", "user", "action", "action_label", "expected", "data"):
                if key not in st:
                    fail("scenario %s step %d is missing '%s'" % (sc["id"], i + 1, key))
            if st["app"] not in APPS_OF_STEPS:
                fail("scenario %s step %d: unknown app %s" % (sc["id"], i + 1, st["app"]))
            if st["action"] == "view" and not st.get("view"):
                fail("scenario %s step %d: a view step needs 'view'" % (sc["id"], i + 1))
    js = ("/* Generated by demo-devices/build.py from demo-devices/scenarios.json - do not edit. */\n"
          "window.WZ_DEVICE_SCENARIOS = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n")
    (SHARED / "scenarios.js").write_text(js, encoding="utf-8")
    return len(scenarios), sum(len(s["steps"]) for s in scenarios)


def safe_script(text):
    return re.sub(r"</(script)", r"<\\/\1", text, flags=re.IGNORECASE)


def inline(html, src_file, built_apps):
    base = src_file.parent

    def css(m):
        p = (base / m.group(1)).resolve()
        if not p.exists():
            fail("%s: stylesheet not found: %s" % (src_file.name, m.group(1)))
        return "<style>/* inlined from %s */\n%s\n</style>" % (p.name, p.read_text(encoding="utf-8"))

    def js(m):
        p = (base / m.group(1)).resolve()
        if not p.exists():
            fail("%s: script not found: %s" % (src_file.name, m.group(1)))
        return "<script>/* inlined from %s */\n%s\n</script>" % (p.name, safe_script(p.read_text(encoding="utf-8")))

    out = LINK_RE.sub(css, html)
    out = SCRIPT_RE.sub(js, out)
    out, n = DATA_RE.subn('<script src="device-demo-data.js"></script>', out)
    if n != 1:
        fail("%s: expected exactly one device-demo-data.js script tag with data-wz-data (found %d)" % (src_file.name, n))
    out = out.replace("<!-- wz:built-apps -->", "<script>window.WZ_BUILT_APPS = %s;</script>" % json.dumps(built_apps))
    if "data-wz-inline" in out:
        fail("%s: an inline marker was not resolved" % src_file.name)
    if re.search(r'(src|href)="https?://', out):
        fail("%s: external URL found – the pack must run offline" % src_file.name)
    return out


def check_design_system():
    general = ROOT.parent / "demo" / "shared"
    for name in ("ui.css", "ui.js"):
        a, b = SHARED / name, general / name
        if b.exists() and a.read_text(encoding="utf-8") != b.read_text(encoding="utf-8"):
            print("  note: shared/%s differs from demo/shared/%s (copy it again to pick up design-system changes)" % (name, name))


def main():
    if not (DATA / "device-demo-data.js").exists():
        fail("data/device-demo-data.js not found (run: node demo-devices/tools/gen-data.js)")
    count, steps = write_scenarios()
    check_design_system()
    DIST.mkdir(exist_ok=True)
    apps = [n for n in APP_ORDER if (SRC / (n + ".html")).exists()]
    shutil.copyfile(DATA / "device-demo-data.js", DIST / "device-demo-data.js")
    report = []
    for name in apps + ["index"]:
        src = SRC / (name + ".html")
        if not src.exists():
            continue
        target = DIST / (name + ".html")
        target.write_text(inline(src.read_text(encoding="utf-8"), src, apps), encoding="utf-8")
        report.append((target.name, target.stat().st_size))
    print("WellnessZ device integration demo pack built in %s" % DIST)
    print("  scenarios: %d (%d steps)" % (count, steps))
    for fname, size in report:
        print("  %-26s %7.1f kB" % (fname, size / 1024))
    print("  %-26s %7.1f kB (demo data file, kept separate)" % ("device-demo-data.js", (DIST / "device-demo-data.js").stat().st_size / 1024))


if __name__ == "__main__":
    main()
