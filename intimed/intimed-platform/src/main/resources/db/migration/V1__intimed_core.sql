-- IntiMed core schema (portable PostgreSQL 16 / H2 2.x in PostgreSQL mode)
create table tenants (
    id            varchar(64) primary key,
    name          varchar(200) not null,
    residency     varchar(64)  not null,
    plan          varchar(64)  not null,
    status        varchar(32)  not null,
    environment   varchar(16)  not null,
    settings      text         not null,
    created_at    timestamp with time zone not null
);

create table tenant_keys (
    tenant_id     varchar(64) primary key,
    wrapped_key   text not null,
    created_at    timestamp with time zone not null
);

create table users (
    id              varchar(64) primary key,
    tenant_id       varchar(64) not null,
    username        varchar(100) not null unique,
    password_hash   varchar(255) not null,
    display_name    varchar(200) not null,
    roles           varchar(500) not null,
    totp_secret     text,
    failed_attempts int not null default 0,
    locked_until    timestamp with time zone,
    created_at      timestamp with time zone not null
);

create table documents (
    tenant_id   varchar(64)  not null,
    kind        varchar(64)  not null,
    id          varchar(128) not null,
    data        text         not null,
    status      varchar(64),
    ref         varchar(256),
    created_at  timestamp with time zone not null,
    updated_at  timestamp with time zone not null,
    version     int not null,
    primary key (tenant_id, kind, id)
);
create index ix_documents_status on documents(tenant_id, kind, status);
create index ix_documents_ref on documents(tenant_id, kind, ref);

-- SC-08 tamper-evident audit: append-only, hash-chained per installation
create table audit_log (
    seq        bigint generated by default as identity primary key,
    tenant_id  varchar(64)  not null,
    ts         timestamp with time zone not null,
    actor      varchar(128) not null,
    action     varchar(128) not null,
    target     varchar(256),
    detail     text,
    prev_hash  varchar(64) not null,
    hash       varchar(64) not null
);
create index ix_audit_tenant on audit_log(tenant_id, seq);

-- IM-E09 metering (connected devices, observations, harness runs) per tenant and day
create table metering (
    tenant_id  varchar(64) not null,
    usage_day  varchar(10) not null,
    meter      varchar(64) not null,
    qty        bigint not null,
    primary key (tenant_id, usage_day, meter)
);
