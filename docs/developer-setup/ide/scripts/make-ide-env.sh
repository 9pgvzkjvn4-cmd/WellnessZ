#!/usr/bin/env bash
# =============================================================================
# Generate the IDE env files for core and BFF from deploy/local/.env - without
# plaintext secrets in run configurations or env files.
#
#   docs/developer-setup/ide/scripts/make-ide-env.sh
#
# Writes (umask 077):
#   ~/.config/wellnessz/core-master.key   core WZ_MASTER_KEY  (mode 600, outside the repository)
#   ~/.config/wellnessz/bff-master.key    BFF  WZ_MASTER_KEY  (mode 600, outside the repository)
#   deploy/local/core.local.env           git-ignored (*.local.env); secrets only as ENC(...)
#   deploy/local/bff.local.env            git-ignored (*.local.env); secrets only as ENC(...)
#
# The applications point WZ_MASTER_KEY_FILE at the key file and decrypt the
# ENC(...) values at start-up (platform/wz-secrets, SecretsEnvironmentPostProcessor).
# Override the key directory with WZ_IDE_KEY_DIR. Re-run after ./deploy/local/down.sh
# --purge or whenever deploy/local/.env changes.
# =============================================================================
set -euo pipefail
# shellcheck source=lib/common.sh
. "$(dirname "$0")/lib/common.sh"
require_dotenv

KEY_DIR="${WZ_IDE_KEY_DIR:-${XDG_CONFIG_HOME:-$HOME/.config}/wellnessz}"
CORE_ENV="$WZ_ROOT/deploy/local/core.local.env"
BFF_ENV="$WZ_ROOT/deploy/local/bff.local.env"
CLASSES="$WZ_ROOT/platform/wz-secrets/target/classes"

umask 077
command -v java >/dev/null || die "java not found - install JDK 21 first"

# Read the values we need (kept in shell variables, never exported or passed as arguments)
need() {
  local v
  v=$(env_value "$WZ_DOTENV" "$1") || die "$1 missing in deploy/local/.env (compare with .env.example)"
  [[ -n $v ]] || die "$1 is empty in deploy/local/.env"
  printf '%s' "$v"
}
CORE_KEY=$(need WZ_MASTER_KEY)
BFF_KEY=$(need WZ_BFF_MASTER_KEY)
PSEUDONYM_KEY=$(need WZ_PSEUDONYM_KEY)
APP_PW=$(need WZ_APP_DB_PASSWORD)
MIGRATOR_PW=$(need WZ_MIGRATOR_DB_PASSWORD)
BFF_PW=$(need WZ_BFF_DB_PASSWORD)
IMAP_PW=$(need WZ_IMAP_PASSWORD)
CLIENT_SECRET=$(need WZ_BFF_CLIENT_SECRET)

mkdir -p "$KEY_DIR"
chmod 700 "$KEY_DIR"
printf '%s\n' "$CORE_KEY" >"$KEY_DIR/core-master.key"
printf '%s\n' "$BFF_KEY" >"$KEY_DIR/bff-master.key"
chmod 600 "$KEY_DIR/core-master.key" "$KEY_DIR/bff-master.key"

if [[ ! -f "$CLASSES/com/wellnessz/secrets/EncryptCli.class" ]]; then
  info "Compiling platform/wz-secrets (first run only)"
  (cd "$WZ_ROOT" && ./mvnw -q -pl platform/wz-secrets -am compile)
fi

# enc KEYFILE PLAINTEXT - plaintext goes through stdin (printf is a shell builtin,
# so it never appears in a process list); EncryptCli prints ENC(...)
enc() {
  local out
  out=$(printf '%s\n' "$2" | env -u WZ_MASTER_KEY WZ_MASTER_KEY_FILE="$1" \
    java -cp "$CLASSES" com.wellnessz.secrets.EncryptCli 2>/dev/null | tail -n 1)
  [[ $out == ENC\(*\) ]] || die "Encryption failed - run tools/encrypt-secret.sh manually to see the error"
  printf '%s' "$out"
}

CK="$KEY_DIR/core-master.key"
BK="$KEY_DIR/bff-master.key"

cat >"$CORE_ENV" <<EOF
# Generated by docs/developer-setup/ide/scripts/make-ide-env.sh - local only, never commit.
# Secrets are ENC(...) values decrypted with the key in WZ_MASTER_KEY_FILE.
SPRING_PROFILES_ACTIVE=local
WZ_MASTER_KEY_FILE=$CK
WZ_PSEUDONYM_KEY=$(enc "$CK" "$PSEUDONYM_KEY")
WZ_DB_USERNAME=wz_app
WZ_DB_PASSWORD=$(enc "$CK" "$APP_PW")
WZ_DB_MIGRATOR_USERNAME=wz_migrator
WZ_DB_MIGRATOR_PASSWORD=$(enc "$CK" "$MIGRATOR_PW")
WZ_EHS_MAILBOX_MODE=imap
WZ_IMAP_HOST=localhost
WZ_IMAP_PORT=3143
WZ_IMAP_USERNAME=ehs-feed@wellnessz.local
WZ_IMAP_PASSWORD=$(enc "$CK" "$IMAP_PW")
WZ_SMTP_HOST=localhost
WZ_SMTP_PORT=1025
EOF

cat >"$BFF_ENV" <<EOF
# Generated by docs/developer-setup/ide/scripts/make-ide-env.sh - local only, never commit.
# The BFF has its own session key; it never holds the core master key.
SPRING_PROFILES_ACTIVE=local
WZ_MASTER_KEY_FILE=$BK
WZ_BFF_DB_USERNAME=wz_bff
WZ_BFF_DB_PASSWORD=$(enc "$BK" "$BFF_PW")
WZ_DB_MIGRATOR_USERNAME=wz_migrator
WZ_DB_MIGRATOR_PASSWORD=$(enc "$BK" "$MIGRATOR_PW")
WZ_BFF_CLIENT_SECRET=$(enc "$BK" "$CLIENT_SECRET")
EOF

chmod 600 "$CORE_ENV" "$BFF_ENV"
info "Wrote $CORE_ENV and $BFF_ENV (mode 600, git-ignored)"
info "Master key files in $KEY_DIR (mode 600)"
